step_launchers_configs() {
    print_step $((++CURRENT_STEP)) "${TOTAL_STEPS}" "Configuring Launchers & Desktop Environment"
    echo ""

    local de="${DE}"
    [[ "${de}" == "kde" ]] && de="KDE" || de="Hyprland"

    if [[ "${DE}" == "hyprland" ]]; then
        configure_hyprland
    elif [[ "${DE}" == "kde" ]]; then
        configure_kde
    fi

    # Termux:API integration
    if cfg_is_true "features.termux_api"; then
        configure_termux_api
    fi

    log_success "Launchers & ${de} configs created"
}

