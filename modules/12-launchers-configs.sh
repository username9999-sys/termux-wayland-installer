configure_termux_api() {
    log_info "Configuring Termux:API integration"

    # Install termux-api if not present
    if ! command -v termux-toast &>/dev/null; then
        execute install_pkg "termux-api" "Termux:API"
    fi

    # Create helper scripts
    execute mkdir -p "${HOME}/.local/bin"

    execute cat > "${HOME}/.local/bin/termux-notify" << 'EOF'
#!/data/data/com.termux/files/usr/bin/bash
# Wrapper for termux-notification with proot support
if [ -n "$PROOT_DISTRO" ]; then
    # Running inside proot
    /data/data/com.termux/files/usr/bin/termux-notification "$@"
else
    # Running in Termux host
    /data/data/com.termux/files/usr/bin/termux-notification "$@"
fi
EOF
    execute chmod +x "${HOME}/.local/bin/termux-notify"

    execute cat > "${HOME}/.local/bin/termux-toast-wrapper" << 'EOF'
#!/data/data/com.termux/files/usr/bin/bash
# Wrapper for termux-toast with proot support
if [ -n "$PROOT_DISTRO" ]; then
    /data/data/com.termux/files/usr/bin/termux-toast "$@"
else
    /data/data/com.termux/files/usr/bin/termux-toast "$@"
fi
EOF
    execute chmod +x "${HOME}/.local/bin/termux-toast-wrapper"

    log_success "Termux:API integration configured"
}

