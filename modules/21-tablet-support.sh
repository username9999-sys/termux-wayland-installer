#!/data/data/com.termux/files/usr/bin/bash
# ============================================================
# termux-wayland-installer - Step: Tablet/Stylus Support
# Configures Wacom, S-Pen, and other tablet devices for Wayland
# ============================================================

step_tablet_support() {
    [[ "${TABLET_SUPPORT:-false}" != "true" ]] && return 0

    print_step $((++CURRENT_STEP)) "${TOTAL_STEPS}" "Configuring Tablet/Stylus Support"
    echo ""

    log_info "Installing tablet packages and configuring input..."

    # Install tablet packages
    local packages=(
        "libwacom|Libwacom (tablet database)"
        "libinput|Libinput (input handling)"
        "kde-cli-tools|KDE CLI Tools (for kcminputrc)"  # For KDE
    )

    local failed=()
    for pkg_spec in "${packages[@]}"; do
        IFS='|' read -r pkg name <<< "${pkg_spec}"
        name="${name:-$pkg}"
        if ! execute install_pkg "${pkg}" "${name}"; then
            failed+=("${name}")
        fi
    done

    if [[ ${#failed[@]} -gt 0 ]]; then
        log_warn "Some tablet packages failed: ${failed[*]}"
    fi

    # Configure udev rules for tablet devices
    configure_tablet_udev_rules

    # Configure libinput for tablets
    configure_libinput_tablet

    # DE-specific configuration
    case "${DE}" in
        hyprland)
            configure_hyprland_tablet
            ;;
        kde)
            configure_kde_tablet
            ;;
    esac

    # Input method tablet config (fcitx5)
    if [[ "${INPUT_METHOD:-false}" == "true" && "${INPUT_METHOD_ENGINE:-fcitx5}" == "fcitx5" ]]; then
        configure_fcitx5_tablet
    fi

    log_success "Tablet/Stylus support configured for ${DE^}"
}

configure_tablet_udev_rules() {
    log_info "Creating udev rules for tablet devices..."

    execute mkdir -p "${HOME}/.config/udev/rules.d"

    # Udev rules for Wacom, S-Pen, and generic tablets
    execute cat > "${HOME}/.config/udev/rules.d/99-tablet.rules" << 'UDEV_EOF'
# Tablet/Stylus udev rules - Auto-generated by termux-wayland-installer
# Wacom devices
ATTRS{name}=="Wacom*", ENV{LIBINPUT_TABLET_TOOL}=="1", TAG+="uaccess"
ATTRS{name}=="Wacom*", ENV{ID_INPUT_TABLET}=="1", TAG+="uaccess"

# Samsung S-Pen
ATTRS{name}=="*S-Pen*", ENV{LIBINPUT_TABLET_TOOL}=="1", TAG+="uaccess"
ATTRS{name}=="*S-Pen*", ENV{ID_INPUT_TABLET}=="1", TAG+="uaccess"
ATTRS{name}=="sec_touchscreen", ENV{LIBINPUT_TABLET_TOOL}=="1", TAG+="uaccess"

# Generic HID tablets
SUBSYSTEM=="hidraw", ATTRS{name}=="*Tablet*", TAG+="uaccess"
SUBSYSTEM=="hidraw", ATTRS{name}=="*tablet*", TAG+="uaccess"
SUBSYSTEM=="hidraw", ATTRS{name}=="*Pen*", TAG+="uaccess"

# Huion, XP-Pen, Gaomon, etc.
ATTRS{name}=="HUION*", ENV{LIBINPUT_TABLET_TOOL}=="1", TAG+="uaccess"
ATTRS{name}=="XP-PEN*", ENV{LIBINPUT_TABLET_TOOL}=="1", TAG+="uaccess"
ATTRS{name}=="GAOMON*", ENV{LIBINPUT_TABLET_TOOL}=="1", TAG+="uaccess"
ATTRS{name}=="VEIKK*", ENV{LIBINPUT_TABLET_TOOL}=="1", TAG+="uaccess"
ATTRS{name}=="UGEE*", ENV{LIBINPUT_TABLET_TOOL}=="1", TAG+="uaccess"

# Set permissions for uinput (for virtual tablet tools)
KERNEL=="uinput", MODE="0660", GROUP="input", TAG+="uaccess"
UDEV_EOF

    log_info "Udev rules created at ~/.config/udev/rules.d/99-tablet.rules"
    log_warn "Note: udev rules require Termux:API or root to take effect immediately"
}

configure_libinput_tablet() {
    log_info "Configuring libinput for tablet support..."

    execute mkdir -p "${HOME}/.config/libinput"

    execute cat > "${HOME}/.config/libinput/libinput.conf" << 'LIBINPUT_EOF'
# Libinput configuration for tablets - Auto-generated by termux-wayland-installer

[tablet]
# Pressure curve (0=linear, 1=soft, 2=hard)
PressureCurve=0

# Mapping mode
MapToOutput=

# Rotation (0=none, 1=90, 2=180, 3=270)
Rotation=0

# Button mapping
ButtonMapping=default

[touchpad]
# Touchpad settings (also affects tablet touch strips)
NaturalScrolling=true
TapToClick=true
TapAndDrag=true
TwoFingerTap=right
ThreeFingerTap=middle
ScrollTwoFingers=true
AccelProfile=adaptive
Speed=0.0

[mouse]
AccelProfile=flat
Speed=0.0

[trackpoint]
AccelProfile=flat
Speed=0.0
LIBINPUT_EOF

    log_info "Libinput config created"
}

configure_hyprland_tablet() {
    log_info "Configuring Hyprland tablet support..."

    execute mkdir -p "${HOME}/.config/hypr"

    # Add tablet config to hyprland.conf (append if exists)
    if [[ -f "${HOME}/.config/hypr/hyprland.conf" ]]; then
        if ! grep -q "tablet {" "${HOME}/.config/hypr/hyprland.conf" 2>/dev/null; then
            execute cat >> "${HOME}/.config/hypr/hyprland.conf" << 'HYPR_TABLET_EOF'

# Tablet/Stylus Configuration
tablet {
    # Pressure sensitivity
    pressure_sensitivity = 1.0

    # Button mapping
    button_mapping = default

    # Map to specific output (empty = auto)
    map_to_output =

    # Rotation (0=none, 1=90, 2=180, 3=270)
    rotation = 0

    # Custom tool mappings
    # tool {
    #     name = "Wacom Intuos Pro"
    #     button {
    #         1 = "BTN_LEFT"
    #         2 = "BTN_RIGHT"
    #     }
    # }
}

# Input method tablet integration (fcitx5)
# See fcitx5 config for virtual keyboard on tablet
HYPR_TABLET_EOF
        fi
    fi

    log_info "Hyprland tablet config added"
}

