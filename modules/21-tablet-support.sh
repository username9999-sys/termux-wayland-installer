configure_fcitx5_tablet() {
    log_info "Configuring fcitx5 for tablet virtual keyboard..."

    execute mkdir -p "${HOME}/.config/fcitx5/profile"

    # Add tablet-specific fcitx5 config
    local profile_file="${HOME}/.config/fcitx5/profile/default"
    
    if [[ -f "${profile_file}" ]]; then
        # Check if tablet section exists
        if ! grep -q "TabletMode" "${profile_file}" 2>/dev/null; then
            cat >> "${profile_file}" << 'FCITX_TABLET_EOF'

# Tablet Mode Configuration
[TabletMode]
# Enable virtual keyboard in tablet mode
EnableVirtualKeyboard=true

# Show virtual keyboard when tablet tool touches surface
ShowOnTabletTool=true

# Keyboard layout for tablet
TabletLayout=us

# Auto-hide timeout (ms)
AutoHideTimeout=3000

# Position (bottom, top, center)
Position=bottom
FCITX_TABLET_EOF
        fi
    else
        # Create profile with tablet config (input method hasn't run yet)
        cat > "${profile_file}" << 'FCITX_TABLET_EOF'
[Groups/0]
Name=Default
Default Layout=us
DefaultIM=keyboard-us

[Groups/0/Items/0]
Name=keyboard-us
Layout=us

[Groups/1]
Name=Chinese
Default Layout=us
DefaultIM=pinyin

[Groups/1/Items/0]
Name=keyboard-us
Layout=us

[Groups/1/Items/1]
Name=pinyin
Layout=us

[Groups/2]
Name=Japanese
Default Layout=us
DefaultIM=anthy

[Groups/2/Items/0]
Name=keyboard-us
Layout=us

[Groups/2/Items/1]
Name=anthy
Layout=us

[Groups/3]
Name=Korean
Default Layout=us
DefaultIM=hangul

[Groups/3/Items/0]
Name=keyboard-us
Layout=us

[Groups/3/Items/1]
Name=hangul
Layout=us

[Hotkeys]
TriggerKey=CTRL_SPACE
SwitchKey=ALT_SPACE

# Tablet Mode Configuration
[TabletMode]
# Enable virtual keyboard in tablet mode
EnableVirtualKeyboard=true

# Show virtual keyboard when tablet tool touches surface
ShowOnTabletTool=true

# Keyboard layout for tablet
TabletLayout=us

# Auto-hide timeout (ms)
AutoHideTimeout=3000

# Position (bottom, top, center)
Position=bottom
FCITX_TABLET_EOF
    fi

    # Create fcitx5 tablet trigger script
    execute mkdir -p "${HOME}/.local/bin"
    cat > "${HOME}/.local/bin/fcitx5-tablet-mode" << 'FCITX_TABLET_SCRIPT_EOF'
#!/data/data/com.termux/files/usr/bin/bash
# fcitx5 Tablet Mode Toggle
# Auto-generated by termux-wayland-installer

CONFIG_FILE="${HOME}/.config/fcitx5/profile/default"

toggle_tablet_mode() {
    if grep -q "EnableVirtualKeyboard=true" "${CONFIG_FILE}" 2>/dev/null; then
        # Disable
        sed -i 's/EnableVirtualKeyboard=true/EnableVirtualKeyboard=false/' "${CONFIG_FILE}"
        sed -i 's/ShowOnTabletTool=true/ShowOnTabletTool=false/' "${CONFIG_FILE}"
        echo "Tablet mode: DISABLED"
    else
        # Enable
        sed -i 's/EnableVirtualKeyboard=false/EnableVirtualKeyboard=true/' "${CONFIG_FILE}"
        sed -i 's/ShowOnTabletTool=false/ShowOnTabletTool=true/' "${CONFIG_FILE}"
        echo "Tablet mode: ENABLED"
    fi

    # Restart fcitx5 if running
    if pgrep -x "fcitx5" >/dev/null 2>&1; then
        fcitx5 -r &
    fi
}

case "${1:-toggle}" in
    on|enable)
        sed -i 's/EnableVirtualKeyboard=false/EnableVirtualKeyboard=true/' "${CONFIG_FILE}"
        sed -i 's/ShowOnTabletTool=false/ShowOnTabletTool=true/' "${CONFIG_FILE}"
        pgrep -x "fcitx5" >/dev/null 2>&1 && fcitx5 -r &
        echo "Tablet mode: ENABLED"
        ;;
    off|disable)
        sed -i 's/EnableVirtualKeyboard=true/EnableVirtualKeyboard=false/' "${CONFIG_FILE}"
        sed -i 's/ShowOnTabletTool=true/ShowOnTabletTool=false/' "${CONFIG_FILE}"
        pgrep -x "fcitx5" >/dev/null 2>&1 && fcitx5 -r &
        echo "Tablet mode: DISABLED"
        ;;
    toggle|*)
        toggle_tablet_mode
        ;;
esac
FCITX_TABLET_SCRIPT_EOF
    execute chmod +x "${HOME}/.local/bin/fcitx5-tablet-mode"

    log_info "fcitx5 tablet mode script created at ~/.local/bin/fcitx5-tablet-mode"
}

# Test tablet detection
test_tablet_detection() {
    log_info "Testing tablet device detection..."

    local found=false

    # Check for Wacom
    if ls /dev/input/by-id/ 2>/dev/null | grep -qi wacom; then
        log_info "  Wacom device detected"
        found=true
    fi

    # Check for S-Pen (Samsung)
    if ls /dev/input/by-id/ 2>/dev/null | grep -qi "s-pen\|spen\|sec_touch"; then
        log_info "  Samsung S-Pen detected"
        found=true
    fi

    # Check for generic tablets
    if ls /dev/input/ 2>/dev/null | grep -q "event"; then
        for event in /dev/input/event*; do
            name=$(udevadm info --query=property --name="${event}" 2>/dev/null | grep "ID_INPUT_TABLET=1" || true)
            if [[ -n "${name}" ]]; then
                log_info "  Tablet device: ${event}"
                found=true
            fi
        done
    fi

    if [[ "${found}" != "true" ]]; then
        log_warn "  No tablet devices detected (this is normal if not connected)"
    fi
}

export -f step_tablet_support configure_tablet_udev_rules configure_libinput_tablet
export -f configure_hyprland_tablet configure_kde_tablet configure_fcitx5_tablet
export -f test_tablet_detection